def _tuple_texts(value: Any) -> tuple[str, ...]:
    if not isinstance(value, (list, tuple, set)):
        return ()
    result: list[str] = []
    seen: set[str] = set()
    for raw in value:
        text = " ".join(str(raw or "").split()).strip()
        if not text or text in seen:
            continue
        seen.add(text)
        result.append(text)
    return tuple(result)


def _verification_mode(value: Any) -> Literal["anchor", "structural", "llm"]:
    mode = str(value or "anchor").strip().lower()
    if mode in {"anchor", "structural", "llm"}:
        return mode  # type: ignore[return-value]
    return "anchor"


def _apply_builtin_metadata(
    builtin: tuple[_ElementDefinition, ...],
) -> tuple[_ElementDefinition, ...]:
    patched: list[_ElementDefinition] = []
    for element in builtin:
        patch = _ELEMENT_METADATA_PATCHES.get(element.element_id)
        if patch:
            patch = dict(patch)
            for key in (
                "requires",
                "excludes",
                "complements",
                "phase_affinity",
                "verification_anchors",
            ):
                patch[key] = _tuple_texts(patch.get(key, ()))
            patch["verification_mode"] = _verification_mode(patch.get("verification_mode"))
            patched.append(replace(element, **patch))
        else:
            patched.append(element)
    return tuple(patched)


_ELEMENT_LIBRARY = _apply_builtin_metadata(_ELEMENT_LIBRARY)


def _repo_root() -> Path:
    for parent in Path(__file__).resolve().parents:
        if (parent / "pyproject.toml").exists() and (parent / "novel_forge").is_dir():
            return parent
    return Path(__file__).resolve().parents[4]


def external_element_library_path() -> Path:
    return _repo_root() / "data" / "element_library.json"


def _load_external_element_library() -> dict[str, dict[str, Any]]:
    try:
        path = external_element_library_path()
        if path.exists():
            import json

            with open(path, encoding="utf-8") as f:
                payload = json.load(f)
            return {item["element_id"]: item for item in payload.get("elements", [])}
    except Exception:
        pass
    return {}


def _merge_with_external(
    builtin: tuple[_ElementDefinition, ...],
) -> tuple[_ElementDefinition, ...]:
    external = _load_external_element_library()
    if not external:
        return builtin
    merged = {element.element_id: element for element in builtin}
    for eid, ext_data in external.items():
        merged[eid] = _ElementDefinition(
            element_id=eid,
            name=ext_data["name"],
            category=ext_data["category"],
            tier=ext_data.get("tier", "extension"),
            description=ext_data["description"],
            rationale=ext_data.get("rationale", ""),
            recommended_genres=tuple(ext_data.get("recommended_genres", [])),
            prompt_hint=ext_data.get("prompt_hint", ""),
            ui_hint=ext_data.get("ui_hint", "checklist"),
            source="external",
            implementation_guide=ext_data.get("implementation_guide", ""),
            verification_anchors=_tuple_texts(ext_data.get("verification_anchors", [])),
            verification_mode=_verification_mode(ext_data.get("verification_mode", "anchor")),
            intensity_hint=ext_data.get("intensity_hint", ""),
            requires=_tuple_texts(ext_data.get("requires", [])),
            excludes=_tuple_texts(ext_data.get("excludes", [])),
            complements=_tuple_texts(ext_data.get("complements", [])),
            phase_affinity=_tuple_texts(ext_data.get("phase_affinity", [])),
        )
    return tuple(merged.values())


