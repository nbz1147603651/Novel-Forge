@dataclass(frozen=True)
class _ElementDefinition:
    element_id: str
    name: str
    category: str
    tier: Literal["required", "extension"]
    description: str
    rationale: str
    recommended_genres: tuple[str, ...]
    prompt_hint: str
    ui_hint: str
    source: Literal["builtin", "external"] = "builtin"
    implementation_guide: str = ""
    verification_anchors: tuple[str, ...] = ()
    verification_mode: Literal["anchor", "structural", "llm"] = "anchor"
    intensity_hint: str = ""
    requires: tuple[str, ...] = ()
    excludes: tuple[str, ...] = ()
    complements: tuple[str, ...] = ()
    phase_affinity: tuple[str, ...] = ()

    def to_card(
        self,
        *,
        reason: str = "",
        selection_source: str = "",
        selection_score: float = 0.0,
        user_weight: float | None = None,
        user_locked: bool = False,
        user_enabled: bool | None = None,
    ) -> BlueprintElementCard:
        return BlueprintElementCard(
            element_id=self.element_id,
            name=self.name,
            category=self.category,
            tier=self.tier,
            description=self.description,
            rationale=self.rationale,
            recommended_genres=list(self.recommended_genres),
            prompt_hint=self.prompt_hint,
            implementation_guide=self.implementation_guide,
            verification_anchors=list(self.verification_anchors),
            verification_mode=self.verification_mode,
            intensity_hint=self.intensity_hint,
            requires=list(self.requires),
            excludes=list(self.excludes),
            complements=list(self.complements),
            phase_affinity=list(self.phase_affinity),
            ui_hint=self.ui_hint,
            selection_reason=reason,
            library_source=self.source,
            selection_source=selection_source,
            selection_score=max(0.0, float(selection_score or 0.0)),
            user_weight=user_weight,
            user_locked=user_locked,
            user_enabled=user_enabled,
        )


