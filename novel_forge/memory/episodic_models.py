"""Data models and helper functions for episodic memory.

Extracted from episodic.py to reduce file size and improve separation of
concerns.  All index dataclasses (EpisodicIndex, OutlinePlotPoint,
CritiqueIndex, VolumeAuditIndex) and supporting types (RelationshipChange,
OutlineContext) live here.
"""

from __future__ import annotations

import hashlib
from collections import Counter
from dataclasses import dataclass, field
from typing import Any

from novel_forge.memory.base import EpisodicResult


@dataclass
class EpisodicIndex:
    """Indexed entry for a chapter or scene."""

    chapter_number: int
    event_summary: str
    scene_index: int = 0  # 0 = chapter-level summary
    full_text: str = ""
    characters: list[str] = field(default_factory=list)
    locations: list[str] = field(default_factory=list)
    event_types: list[str] = field(default_factory=list)  # conflict, revelation, decision, etc.
    emotional_tone: str = ""
    timestamp_in_story: str = ""
    keywords: list[str] = field(default_factory=list)
    embedding: list[float] = field(default_factory=list)  # Semantic embedding vector
    metadata: dict[str, Any] = field(default_factory=dict)

    def signature(self) -> str:
        """Generate a unique signature for deduplication."""
        text = f"{self.chapter_number}:{self.scene_index}:{self.event_summary}"
        return hashlib.md5(text.encode("utf-8")).hexdigest()


