# === 改进5: 失败模式总结和经验教训生成辅助函数 ===


def summarize_failure_pattern(critique: CritiqueIndex) -> str | None:
    """Summarize failure pattern from multiple repair attempts.

    Analyzes repair_attempts to find common new issues introduced.
    Returns a summary string if patterns are found, None otherwise.
    """
    attempts = critique.repair_attempts

    if len(attempts) < 2:
        return None

    # Analyze common characteristics
    common_new_issues: Counter[str] = Counter()
    for attempt in attempts:
        for issue_type in attempt.get("new_issues_introduced", []):
            common_new_issues[issue_type] += 1

    # Find frequent issue types (appeared >= 2 times)
    frequent_issues = [issue for issue, count in common_new_issues.items() if count >= 2]

    if frequent_issues:
        return f"修复{critique.issue_type}时，容易引入以下问题：{', '.join(frequent_issues)}"

    return None


def generate_lesson_learned(critique: CritiqueIndex) -> str | None:
    """Generate cross-chapter reusable lesson.

    Returns a lesson string if patterns are found, None otherwise.
    """
    attempts = critique.repair_attempts
    pattern = critique.failure_pattern

    if not pattern:
        return None

    # Find successful repair strategy (if any)
    successful_attempts = [a for a in attempts if a.get("result") == "success"]

    if successful_attempts:
        best_strategy = successful_attempts[-1].get("strategy", "unknown")
        return (
            f"建议使用{best_strategy}策略修复{critique.issue_type}，避免同时修改过多内容。{pattern}"
        )

    return f"修复{critique.issue_type}时需要格外小心，{pattern}建议缩小修复范围，分多轮进行。"


@dataclass
class RelationshipChange:
    """Tracks a relationship change between characters."""

    character_a: str
    character_b: str
    chapter: int
    change_type: str  # trust_up, trust_down, tension_up, tension_down, new_relation
    description: str = ""
    current_trust: float = 0.5
    current_tension: float = 0.5


@dataclass
class OutlineContext:
    """Comprehensive context for outline generation."""

    recent_plot_points: list[OutlinePlotPoint] = field(default_factory=list)
    relationship_changes: list[RelationshipChange] = field(default_factory=list)
    similar_events: list[EpisodicResult] = field(default_factory=list)
    unresolved_questions: list[str] = field(default_factory=list)
    theme_occurrences: dict[str, list[int]] = field(default_factory=dict)
    character_states: dict[str, dict[str, Any]] = field(default_factory=dict)
    chapter_summary: str = ""

    def to_prompt_text(self) -> str:
        """Convert to human-readable prompt text."""
        lines = []

        if self.recent_plot_points:
            lines.append("### 最近章节情节点")
            for pp in self.recent_plot_points[-5:]:
                lines.append(f"- 第{pp.chapter_number}章：{pp.plot_point[:50]}...")
                if pp.event_type:
                    lines.append(f"  [类型: {pp.event_type}]")

        if self.relationship_changes:
            lines.append("\n### 关系变化")
            for rel in self.relationship_changes[-5:]:
                lines.append(
                    f"- 第{rel.chapter}章：{rel.character_a} ↔ {rel.character_b}: {rel.change_type}"
                )

        if self.similar_events:
            lines.append("\n### 相似历史情节（供参考）")
            for evt in self.similar_events[:3]:
                lines.append(f"- 第{evt.chapter_number}章：{evt.event_summary[:50]}...")

        if self.unresolved_questions:
            lines.append("\n### 待解决悬念")
            for q in self.unresolved_questions[-3:]:
                lines.append(f"- {q}")

        if self.theme_occurrences:
            lines.append("\n### 主题出现情况")
            for theme, chapters in list(self.theme_occurrences.items())[-3:]:
                lines.append(f"- {theme}: 第{', '.join(map(str, chapters[-3:]))}章")

        return "\n".join(lines)


