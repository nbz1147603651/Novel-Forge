/** Pick the string for the given locale from a dict entry. */
export function pick(locale: Locale, entry: DictEntry): string {
  return entry[locale];
}

/**
 * Translate a key for the given locale, with optional interpolation.
 * Interpolation uses `{placeholder}` syntax in the dict value.
 */
export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const entry = DICT[key];
  if (!entry) return key; // fallback: return key itself if missing
  let text = entry[locale];
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}
