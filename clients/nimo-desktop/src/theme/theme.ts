const themeById = new Map(desktopThemes.map((theme) => [theme.id, theme]));
export const legacyThemeStorageKey = "nimo-ui-parity.theme";
const projectedThemeByRoot = new WeakMap<object, ThemeId>();

const darkThemeIds = new Set<ThemeId>([
  "twilight_ink",
  "indigo_night",
  "pine_soot",
]);

export type ThemeAppearance = "light" | "dark";

export function themeAppearance(themeId: ThemeId): ThemeAppearance {
  return darkThemeIds.has(themeId) ? "dark" : "light";
}

export function normalizeThemeId(candidate: string | null | undefined): ThemeId {
  return themeById.has(candidate as ThemeId) ? candidate as ThemeId : "narrative_ember";
}

export function loadStoredTheme(): ThemeId {
  if (typeof window === "undefined") return "narrative_ember";
  return normalizeThemeId(window.localStorage.getItem(legacyThemeStorageKey));
}

export function themeDefinition(themeId: ThemeId): ThemeDefinition {
  return themeById.get(themeId) ?? themeById.get("narrative_ember")!;
}

export function applyTheme(
  themeId: ThemeId,
  options: { readonly persistLegacy?: boolean; readonly contrast?: "standard" | "high" } = {},
): ThemeDefinition {
  const theme = themeById.get(themeId) ?? themeById.get("narrative_ember")!;
  const root = document.documentElement;

  // Theme selection also changes contrast/mode preferences. Avoid writing the
  // full token catalog again when the active palette did not actually change.
  if (projectedThemeByRoot.get(root) !== theme.id) {
    for (const [token, value] of Object.entries(theme.tokens)) {
      root.style.setProperty(`--nf-${token.replaceAll(".", "-")}`, value);
    }
    projectedThemeByRoot.set(root, theme.id);
  }
  root.dataset.theme = theme.id;
  root.dataset.colorScheme = themeAppearance(theme.id);
  root.dataset.contrast = options.contrast ?? "standard";
  root.style.colorScheme = themeAppearance(theme.id);
  if (options.persistLegacy ?? true) {
    window.localStorage.setItem(legacyThemeStorageKey, theme.id);
  }
  return theme;
}
